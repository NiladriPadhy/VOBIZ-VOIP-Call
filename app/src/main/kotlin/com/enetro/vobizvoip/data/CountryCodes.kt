package com.enetro.vobizvoip.data

/** A dialing region: ISO 3166-1 alpha-2 code, E.164 calling code, and display name. */
data class Country(
    val iso: String,
    val callingCode: String,
    val name: String,
) {
    /** Unicode regional-indicator flag derived from the ISO code, e.g. "IN" -> 🇮🇳. */
    val flag: String
        get() = iso.uppercase()
            .map { Character.toChars(0x1F1E6 + (it - 'A')) }
            .joinToString("") { String(it) }

    val label: String get() = "$flag  $name (+$callingCode)"
}

